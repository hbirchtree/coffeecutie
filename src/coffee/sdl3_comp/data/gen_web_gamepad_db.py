#!/usr/bin/env python3
"""Generate web_gamepad_db.h from the vendored gamecontrollerdb.txt.

Browsers expose unrecognized pads through joydev ordering on Linux, which
matches SDL's Linux button/axis order except that hats are extra axes.
Usage: gen_web_gamepad_db.py gamecontrollerdb.txt <upstream sha> > out.h
"""
import collections
import re
import sys

HAT_AXIS = {1: ("-", 1), 2: ("+", 0), 4: ("+", 1), 8: ("-", 0)}


def vid_pid(guid):
    try:
        b = bytes.fromhex(guid)
    except ValueError:
        return None
    bus = int.from_bytes(b[0:2], "little")
    if len(b) != 16 or not bus or b[6:8] != b"\0\0" or b[10:12] != b"\0\0":
        return None
    return int.from_bytes(b[4:6], "little"), int.from_bytes(b[8:10], "little")


def web_guid(vid, pid):
    # SDL_CreateJoystickGUID(bus=0, vid, pid, version=0), CRC cleared
    le = lambda v: v.to_bytes(2, "little").hex()
    return f"00000000{le(vid)}0000{le(pid)}000000000000"


def rewrite_hats(fields):
    axes = [int(m) for f in fields for m in re.findall(r":[+-]?a(\d+)", f)]
    first_hat_axis = max(axes, default=-1) + 1
    out = []
    for f in fields:
        m = re.fullmatch(r"([^:]+):h(\d+)\.(\d+)", f)
        if not m:
            out.append(f)
            continue
        hat, value = int(m.group(2)), int(m.group(3))
        if value not in HAT_AXIS:
            continue
        sign, offset = HAT_AXIS[value]
        out.append(f"{m.group(1)}:{sign}a{first_hat_axis + 2 * hat + offset}")
    return out


def main():
    src, sha = sys.argv[1], sys.argv[2]
    pads = collections.defaultdict(list)
    for line in open(src, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#") or "platform:Linux," not in line:
            continue
        guid, name, *fields = [f for f in line.split(",") if f]
        key = vid_pid(guid)
        if not key:
            continue
        fields = [f for f in fields if not f.startswith(("platform:", "crc:"))]
        pads[key].append((name, tuple(fields)))

    entries = []
    for (vid, pid), variants in pads.items():
        counts = collections.Counter(f for _, f in variants)
        fields = max(counts, key=lambda f: counts[f])
        name = next(n for n, f in variants if f == fields)
        mapping = ",".join([web_guid(vid, pid), "*", *rewrite_hats(fields)])
        entries.append((mapping + ",", name))
    entries.sort()

    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    print("// Generated by gen_web_gamepad_db.py, do not edit")
    print(f"// Source: mdqinc/SDL_GameControllerDB@{sha} (Linux entries)")
    print("// clang-format off")
    print("#pragma once\n")
    print("#include <array>\n#include <string_view>\n")
    print("namespace sdl3::web_gamepad_db {\n")
    print("using namespace std::string_view_literals;\n")
    print(f"constexpr std::array<std::string_view, {len(entries)}> mappings = {{")
    for mapping, name in entries:
        print(f'    "{esc(mapping)}"sv, // {name}')
    print("};\n")
    print("} // namespace sdl3::web_gamepad_db")


if __name__ == "__main__":
    main()
