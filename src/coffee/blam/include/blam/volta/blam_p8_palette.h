/*!
 * \brief Expand P8 indices into ARGB8 pixels in D3DCOLOR byte order.
 *
 * The NV2A expanded the palette ahead of the texture filter, so an index image
 * must be expanded before it is filtered, scaled or mipped -- interpolating
 * indices lands on unrelated entries. Works on caller-provided spans so the
 * destination can be a temporary or a mapped upload buffer; `dst` must hold
 * four bytes per index.
 */
inline bool expand_p8(Span<const u8> src, Span<vecb4> dst)
{
    if(dst.size() < src.size())
        return false;
    for(size_t i = 0; i < src.size(); i++)
        std::copy_n(
            p8_bump_palette.begin() + src[i], 1, dst.begin() + i);
    return true;
}

