/*! Expand P8 indices into RGBA8 normals, ahead of any filtering */
inline bool expand_p8(Span<const u8> src, Span<vecb4> dst)
{
    if(dst.size() < src.size())
        return false;
    for(size_t i = 0; i < src.size(); i++)
        dst[i] = p8_bump_palette[src[i]];
    return true;
}

